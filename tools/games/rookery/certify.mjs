import { readFileSync, writeFileSync } from 'node:fs';
import { NAPS, SPECS } from '../../../src/games/rookery/levels.js';
import { initial, buildBoard } from '../../../src/games/rookery/rules.js';
import { solve, replay } from '../../../src/games/rookery/solver.js';

export function certify(b) {
  const route=solve(b);
  if(!route)throw Error('Unreachable sleep key: '+b.name);
  const {events}=replay(b,route.path);
  const counter=b.feature==='word'?solve(buildBoard({...SPECS[b.id-1],word:''})):solve(b,initial(b),b.feature);
  return {id:b.id,par:route.path.length,without:counter?.path.length??null,witness:route.path,
    habits:[...new Set(events.flatMap(e=>[e.kind,e.slide?'slide':'',e.letter?'type':'']).filter(Boolean))]};
}
const proof=NAPS.map(certify);
const text='// Generated by tools/games/rookery/certify.mjs from the 45 hand-authored maps.\nexport const PROOFS='+JSON.stringify(proof,null,0).replaceAll('},{','},\n{')+';\n';
const path=new URL('../../../src/games/rookery/proofs.js',import.meta.url);
if(process.argv.includes('--check')){
  if(readFileSync(path,'utf8').replaceAll('\r','')!==text)throw Error('Stale witnesses; run this script once without --check.');
}else writeFileSync(path,text);
console.log('Certified '+proof.length+' naps, '+proof.reduce((s,p)=>s+p.par,0)+' shortest-path decisions.');