"""AGI games' fonts (2026-10-19): the two fonts Ride 'Em, AGI! draws its words with (agi1.app/games/rideemagi), subset to
what the game writes and saved as WOFF2 into public/fonts/games/ (self-hosted like the site's other fonts: nothing from
Google's servers, so the site's CSP stays font-src 'self'). Both are free under the SIL Open Font License; their license
files sit beside them.

  Mochiy Pop One (400)            the game's display font (titles, numbers, signs in its worlds)
  M PLUS Rounded 1c (500, 800)    its words (menus, cards, buttons); canvas asks for 700 too, which takes the 800

Mochiy Pop One has no stars (★ ☆, the game's level stars), so the game names M PLUS Rounded 1c right after it: browsers
take a letter a font doesn't have from the next one in the list, in the page and on a canvas alike.

It also writes their @font-face rules, src/games/rideemagi/fonts.css, each with the characters its file really has
(unicode-range), so a browser asks the next font for a star without downloading Mochiy first.

Run (fonttools with brotli; the fonts from Google Fonts, here as the npm packages @expo-google-fonts/<family> 0.4.x, which
ship them unchanged):
    python3 tools/games/game-fonts.py <folder with node_modules/@expo-google-fonts>
A changed font gets a new file name (public/fonts is cached a year): raise VERSION (fonts.css follows by itself).
"""
import sys, os
from fontTools import subset
from fontTools.ttLib import TTFont

VERSION = 'v1'
HERE = os.path.dirname(__file__)
ROOT = os.path.join(HERE, '..', '..', 'public', 'fonts', 'games')
CSS = os.path.join(HERE, '..', '..', 'src', 'games', 'rideemagi', 'fonts.css')

# What the game writes (every letter in its code, checked by tests/arcade.test.js), with room to spare: ASCII, Latin-1,
# general punctuation, arrows, its stars and its music note.
RANGES = [(0x20, 0x7E), (0xA0, 0xFF), (0x2010, 0x2027), (0x2030, 0x203A), (0x2190, 0x2193), (0x2605, 0x2606),
          (0x266A, 0x266A)]

#           its file                                                      its license             family               weight
FONTS = {
    'mochiy': ('mochiy-pop-one/400Regular/MochiyPopOne_400Regular.ttf', 'MochiyPopOne-OFL.txt', 'Mochiy Pop One', 400),
    'mplus-500': ('m-plus-rounded-1c/500Medium/MPLUSRounded1c_500Medium.ttf', 'MPLUSRounded1c-OFL.txt', 'M PLUS Rounded 1c', 500),
    'mplus-800': ('m-plus-rounded-1c/800ExtraBold/MPLUSRounded1c_800ExtraBold.ttf', 'MPLUSRounded1c-OFL.txt',
                  'M PLUS Rounded 1c', 800),
}


def unicodes(ranges):
    out = []
    for a, b in ranges:
        out.extend(range(a, b + 1))
    return out


def unicode_range(codes):
    """The characters as CSS's unicode-range: runs of neighbours as U+A-B."""
    codes = sorted(codes)
    runs, start, prev = [], codes[0], codes[0]
    for c in codes[1:] + [None]:
        if c is not None and c == prev + 1:
            prev = c
            continue
        runs.append('U+%X' % start if start == prev else 'U+%X-%X' % (start, prev))
        if c is not None:
            start = prev = c
    return ', '.join(runs)


def main(src):
    os.makedirs(ROOT, exist_ok=True)
    css = ['/* GENERATED by tools/games/game-fonts.py: the game\'s own fonts, self-hosted (SIL Open Font License, their\n'
           '   license files beside them in public/fonts/games/). Each with the characters its file has. Don\'t edit. */\n']
    for key, (rel, lic, family, weight) in FONTS.items():
        path = os.path.join(src, 'node_modules', '@expo-google-fonts', rel)
        font = TTFont(path, recalcTimestamp=False)  # the same bytes every run
        cmap = font.getBestCmap()
        wanted = unicodes(RANGES)
        have = [u for u in wanted if u in cmap]
        opts = subset.Options()
        opts.flavor = 'woff2'
        opts.layout_features = ['kern', 'liga', 'ccmp', 'mark', 'mkmk', 'palt']
        opts.hinting = False
        opts.desubroutinize = True
        opts.name_IDs = ['*']
        opts.name_languages = ['*']
        opts.notdef_outline = True
        opts.drop_tables += ['DSIG']
        s = subset.Subsetter(opts)
        s.populate(unicodes=have)
        s.subset(font)
        out = os.path.join(ROOT, f'{key}-{VERSION}.woff2')
        font.flavor = 'woff2'
        font.save(out)
        print(f'{key}: {len(have)} characters, {os.path.getsize(out)} bytes')
        # its license, beside it
        pkg = os.path.join(src, 'node_modules', '@expo-google-fonts', rel.split('/')[0], 'LICENSE_FONT')
        with open(pkg, 'rb') as f, open(os.path.join(ROOT, lic), 'wb') as g:
            g.write(f.read())
        css.append('@font-face {\n'
                   f'  font-family: "{family}";\n'
                   f'  src: url("/fonts/games/{key}-{VERSION}.woff2") format("woff2");\n'
                   f'  font-weight: {weight};\n'
                   '  font-style: normal;\n'
                   '  font-display: swap;\n'
                   f'  unicode-range: {unicode_range(have)};\n'
                   '}\n')
    os.makedirs(os.path.dirname(CSS), exist_ok=True)
    with open(CSS, 'w', encoding='utf-8') as f:
        f.write(''.join(css))


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else '.')
