export function refineForeheadC(character, source, mask) {
  for (const anchors of rows[character] || []) {
    for (let segment = 0; segment < anchors.length - 1; segment++) {
      const [y0, left0, right0] = anchors[segment];
      const [y1, left1, right1] = anchors[segment + 1];
      for (let y = y0; y <= y1; y++) {
        const fraction = (y - y0) / (y1 - y0);
        const left = Math.round(left0 + (left1 - left0) * fraction);
        const right = Math.round(right0 + (right1 - right0) * fraction);
        for (let x = left; x <= right; x++) {
          if (source[(y * 512 + x) * 4 + 3]) mask[y * 512 + x] = 1;
        }
      }
    }
  }
  return mask;
}
