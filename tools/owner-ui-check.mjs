// Development-only browser acceptance checks against tools/owner-preview.mjs.
// Set OWNER_PLAYWRIGHT_MODULE to a file: URL when Playwright is provided by a bundled runtime.
const { chromium } = await import(process.env.OWNER_PLAYWRIGHT_MODULE || 'playwright');
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const base = 'http://127.0.0.1:5179';
await mkdir('tools/owner-qa', { recursive: true });
const browser = await chromium.launch({ ...(process.env.OWNER_BROWSER_PATH ? { executablePath: process.env.OWNER_BROWSER_PATH } : {}), headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1100 } });
await context.route('**/*', route => { const u = new URL(route.request().url()); return u.origin === base || ['data:','blob:'].includes(u.protocol) ? route.continue() : route.abort(); });
const page = await context.newPage();
await context.addInitScript(()=>{window.__ownerMessages=[];addEventListener('message',e=>{if(e.data?.type?.startsWith('agi-owner'))window.__ownerMessages.push(e.data);});});
const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  const fake=await (await context.request.get(`${base}/__owner-test/session`)).json();
  const current=await (await context.request.post(`${base}/api/wallet`,{data:{action:'site-owner',session:fake.session}})).json();
  if(current.revision)await context.request.post(`${base}/api/wallet`,{data:{action:'site-restore',session:fake.session,revision:current.revision,targetRevision:0}});
  await page.goto(`${base}/owner`);
  await page.locator('[data-owner-gate]').waitFor({state:'visible'});
  await page.screenshot({ path:'tools/owner-qa/signed-out.png', fullPage:true });
  await page.goto(`${base}/__owner-test`);
  await page.getByRole('button',{name:'Open as the owner',exact:true}).click();
  await page.locator('[data-owner-workspace]').waitFor({state:'visible'});
  await page.getByRole('button',{name:'Her world',exact:true}).click();
  await page.locator('.oc-item-list button').first().waitFor();
  await page.screenshot({path:'tools/owner-qa/desktop-editor.png',fullPage:true});
  const frame = page.frameLocator('[data-owner-preview]');
  const initial = await frame.locator('.lp-eco > ul > li').count();
  await page.locator('.oc-item-list button').first().click();
  await page.getByLabel('Entry name',{exact:true}).fill('Talk with her');
  await page.getByLabel('Entry description',{exact:true}).fill('A place to chat');
  await frame.locator('.lp-eco > ul > li').first().getByText('A place to chat',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Remove item',exact:true}).click();
  await frame.locator('.lp-eco > ul > li[data-owner-hidden="true"]').first().waitFor({state:'attached'});
  await page.getByRole('button',{name:'Publish changes',exact:true}).click();
  await page.getByText('Published. Visitors will see').waitFor();
  const visitor = await context.newPage();
  await visitor.goto(base);
  await visitor.locator('.lp-eco > ul > li[data-owner-hidden="true"]').first().waitFor({state:'attached'});
  assert.equal(await visitor.locator('.lp-eco > ul > li:not([data-owner-hidden="true"])').count(), initial-1);
  await visitor.close();
  await page.getByRole('button',{name:'+ Her world entry',exact:true}).click();
  await page.getByLabel('Title',{exact:true}).fill('A new destination');
  await page.getByLabel('Link address',{exact:true}).fill('/roadmap');
  await frame.locator('.owner-world-item').getByText('A new destination').waitFor();
  await page.getByRole('button',{name:'Publish changes',exact:true}).click();
  await page.getByText('Published. Visitors will see').waitFor();
  await page.getByRole('button',{name:'Add a page',exact:true}).click();
  await page.getByLabel('Page title',{exact:true}).fill('Owner test page');
  await page.getByLabel('Address after /p/',{exact:true}).fill('owner-test-page');
  await page.getByRole('button',{name:'Create page',exact:true}).click();
  await page.getByRole('button',{name:'+ Add section',exact:true}).click();
  await page.getByLabel('Title',{exact:true}).fill('A new section');
  await page.getByLabel('Text',{exact:true}).fill('This content was created using the owner editor.');
  const png=await page.evaluate(()=>{const c=document.createElement('canvas');c.width=16;c.height=16;const ctx=c.getContext('2d');ctx.fillStyle='#ff5c93';ctx.fillRect(0,0,16,16);return c.toDataURL('image/png').split(',')[1];});
  await page.locator('input[type=file]').setInputFiles({name:'test.png',mimeType:'image/png',buffer:Buffer.from(png,'base64')});
  await page.getByText('Image added to your draft.',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Publish changes',exact:true}).click();
  await page.getByText('Published. Visitors will see').waitFor();
  const custom = await context.newPage();
  const response = await custom.goto(`${base}/p/owner-test-page`);
  assert.equal(response.status(),200);
  await custom.getByRole('heading',{name:'A new section',exact:true}).waitFor();
  assert.match(await custom.locator('.site-content-block img').getAttribute('src'),/^data:image\/webp;/);
  assert.equal(await custom.locator('[data-owner-loading]').isVisible(),false);
  await custom.screenshot({path:'tools/owner-qa/custom-page.png',fullPage:true});
  await custom.close();
  await page.setViewportSize({width:390,height:844});
  await page.locator('[data-owner-title]').click();
  await page.screenshot({path:'tools/owner-qa/mobile-editor.png',fullPage:true});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'No horizontal overflow on phone');
  await page.setViewportSize({width:1440,height:1100});
  await page.getByRole('tab',{name:'History',exact:true}).click();
  const original=page.locator('.oc-card').filter({has:page.getByRole('heading',{name:'Version 0',exact:true})});
  await original.getByRole('button',{name:'Restore this version'}).click();
  await page.getByRole('button',{name:'Restore version',exact:true}).click();
  await page.getByText('Earlier version restored and published.').waitFor();
  await page.goto(`${base}/__owner-test`);
  await page.getByRole('button',{name:'Try a different wallet'}).click();
  await page.getByText('This is not the owner wallet.').waitFor();
  assert.equal(await page.locator('[data-owner-workspace]').isVisible(),false);
  assert.deepEqual(errors,[]);
  console.log('PASS: signed-out/wrong-wallet gates, Her world edit/remove/add/save, public reload, custom page/section/uploaded image, mobile width, history restore; no editor page errors.');
} catch(error) {
  console.log('UI',await page.locator('[data-owner-controls]').innerText());
  console.log('STATUS',await page.locator('[data-owner-message]').innerText());
  console.log('FRAME',await page.frames()[1]?.evaluate(()=>({url:location.href,messages:window.__ownerMessages?.slice(-3),hidden:[...document.querySelectorAll('[data-owner-hidden]')].map(n=>[n.tagName,n.className,n.textContent.slice(0,50)])})));
  console.log('ERRORS',errors);
  await page.screenshot({path:'tools/owner-qa/failure.png',fullPage:true});throw error;
} finally { await browser.close(); }
