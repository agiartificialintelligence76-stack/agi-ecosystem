export const frames=stages.map(([name,target,left,right],i)=>{
  const gallery=Math.floor(i/8), boards=[left,right].map(s=>s.replaceAll('/',''));
  if(boards.some(b=>b.length!==25||b.indexOf('@')<0))throw Error(name+' has a torn stage');
  return {id:i,name,target,gallery,size:5,boards:boards.map(b=>b.replace('@','.')),start:boards.map(b=>b.indexOf('@')),
    transform:gallery===1?(i%3===1?'left':'right'):gallery===2?'same':gallery===3?(i%2?'right':'mirror'):i>=35?'reverse':'mirror',
    delay:gallery===2||i===30||i===38,need:(boards[0].includes('P')?1:0)|(boards[1].includes('P')?2:0),exchange:boards.some(b=>b.includes('R'))};
});
