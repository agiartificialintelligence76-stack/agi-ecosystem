for (const [i, l] of LEVELS.entries()) {
  l.world = Number(l.id[0]);
  l.index = i;
  l.par = { epochs: l.sol.length, ticks: l.sol.reduce((s, e) => s + e.length, 0) };
}
export const levelById = (id) => LEVELS.find((l) => l.id === id) || null;
